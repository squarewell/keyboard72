#!/usr/bin/env python3
"""Build fastlibc.c and vfpfloat.c into ../fastlibc_blob.h.

The blob is ARM32 code linked at a fixed guest address and loaded into the
emulator's memory: libc routines (memcpy, strcmp, malloc...) that run inside
the emulator instead of crossing into the host, and VFP versions of the
engine's soft-float routines. Requires clang, ld.lld, llvm-objcopy and llvm-nm.
"""
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
BASE = 0x02300000


def build():
    with tempfile.TemporaryDirectory() as tmp:
        elf = Path(tmp) / 'fastlibc.elf'
        binary = Path(tmp) / 'fastlibc.bin'
        objs = []
        # vfpfloat.c keeps the soft-float calling convention but uses VFP instructions.
        for source, float_flags in (('fastlibc.c', ['-mfloat-abi=soft']),
                                    ('vfpfloat.c', ['-mfloat-abi=softfp', '-mfpu=vfpv3-d16',
                                                    '-ffp-contract=off'])):
            objs.append(Path(tmp) / (source[:-2] + '.o'))
            subprocess.check_call(['clang', '--target=armv7a-none-eabi', '-marm', *float_flags,
                                   '-O2', '-ffreestanding', '-fno-builtin', '-fno-stack-protector',
                                   '-c', str(HERE / source), '-o', str(objs[-1])])
        subprocess.check_call(['ld.lld', '--no-undefined', '-e', '0', f'-Ttext={BASE:#x}',
                               *map(str, objs), '-o', str(elf)])
        subprocess.check_call(['llvm-objcopy', '-O', 'binary', '--only-section=.text', str(elf), str(binary)])
        symbols = {}
        for line in subprocess.check_output(['llvm-nm', '--defined-only', str(elf)], text=True).splitlines():
            address, kind, name = line.split()
            if kind in 'Tt' and name.startswith('fast_'):
                symbols[name] = int(address, 16)
        blob = binary.read_bytes()
    write_header(symbols, blob)
    print(f'built {len(symbols)} functions, {len(blob)} bytes')


def write_header(symbols, blob):
    lines = ['// Generated by native/build_native.py',
             '// from fastlibc.c: guest (ARM32) code linked at a fixed guest address.',
             '#pragma once', '#include <cstdint>', '', 'namespace nin {',
             f'constexpr uint32_t kFastlibcBase = {BASE:#010x};']
    for name, address in sorted(symbols.items()):
        camel = ''.join(part.capitalize() for part in name[len('fast_'):].split('_'))
        lines.append(f'constexpr uint32_t kFastlibc{camel} = {address:#010x};')
    lines.append('alignas(4) static const unsigned char kFastlibcBlob[] = {')
    for i in range(0, len(blob), 16):
        lines.append('    ' + ', '.join(f'{b:#04x}' for b in blob[i:i + 16]) + ',')
    lines += ['};', '}  // namespace nin', '']
    (HERE.parent / 'fastlibc_blob.h').write_text('\n'.join(lines))


if __name__ == '__main__':
    build()
